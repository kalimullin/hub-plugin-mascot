// Формы маскота — векторные «облачка» из кругов (реф владельца 06.10): тело — круги одной заливки, глаза — белые овалы.
// viewBox 0 0 100 100; eyes — центры глаз. Меняется форма — правится только этот файл.
const ring = (cx, cy, dist, r, n, start = -90) => Array.from({ length: n }, (_, i) => {
  const a = ((start + (360 / n) * i) * Math.PI) / 180;
  return [cx + dist * Math.cos(a), cy + dist * Math.sin(a), r];
});

